/** 나라별로 카드 이름 문자열을 성/이 조각으로 되돌린다. build-roster.mjs가 만든 조합을 그대로 되짚는다. */
function splitName(name: string, nation: string): { first: string; last: string } | null {
  if (nation === '대한민국') return null
  const parts = name.split(' ')
  if (parts.length !== 2) return null
  return { first: parts[0], last: parts[1] }
}

/**
 * 카드 하나의 이름·클럽·나라로부터 "이 카드가 빗댄 것으로 보이는" 실제
 * 클럽·선수 추정을 만든다. 확실한 근거가 없으면 그 부분은 생략한다.
 */
export function realHintFor(name: string, club: string, nation: string): string | null {
  // Squad-based cards map 1:1 (data/squads/*.json) — no guessing needed.
  const exact = SQUAD_REAL_HINTS[name]
  if (exact) return `선수: ${exact}`
  const direct = HAND_WRITTEN_REAL_HINTS[name]
  if (direct) return `선수: ${direct}${CLUB_REAL_HINTS[club] ? ` · 클럽: ${CLUB_REAL_HINTS[club]}` : ''}`

  const clubHint = CLUB_REAL_HINTS[club]
  const pool = NAME_REAL_HINTS[nation]
  const split = pool ? splitName(name, nation) : null
  const firstHint = split ? pool.first[split.first] : null
  const lastHint = split ? pool.last[split.last] : null

  const parts: string[] = []
  if (clubHint) parts.push(`클럽: ${clubHint}`)
  if (firstHint || lastHint) {
    const playerBits = [firstHint, lastHint].filter((value, index, arr) => value && arr.indexOf(value) === index)
    if (playerBits.length) parts.push(`선수: ${playerBits.join(' + ')}`)
  }
  return parts.length ? parts.join(' · ') : null
}
